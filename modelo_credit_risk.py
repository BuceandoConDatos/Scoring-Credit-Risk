def analizar_correlaciones(df, target_col='TARGET_60D_12M', umbral=0.85):
    """
    Calcula correlaciones absolutas, imprime pares que superan el umbral
    y muestra un mapa de calor (heatmap) enfocado en esas variables.
    """
    # 1. Calculamos la matriz de correlación (quitando el Target)
    corr_matrix = df.drop(columns=[target_col]).corr().abs()

    # 2. Buscamos las parejas con correlación mayor al umbral
    alto_corr = np.where(corr_matrix > umbral)
    parejas = [(corr_matrix.columns[x], corr_matrix.columns[y], corr_matrix.iloc[x, y])
               for x, y in zip(*alto_corr) if x != y and x < y]

    # 3. Imprimimos los resultados en texto
    print(f"--- Variables con correlación > {umbral} ---")
    if not parejas:
        print("No se encontraron variables que superen este umbral.")
        return # Salimos de la función si no hay nada que graficar

    for p in parejas:
        print(f"{p[0]} y {p[1]} -> Correlación: {p[2]:.2f}")

    # 4. Preparamos los datos para el gráfico
    # Extraemos solo los nombres de las variables que superaron el umbral
    columnas_implicadas = list(set([p[0] for p in parejas] + [p[1] for p in parejas]))

    # Filtramos la matriz para que solo tenga estas columnas
    matriz_filtrada = corr_matrix.loc[columnas_implicadas, columnas_implicadas]

    # 5. Creamos el gráfico (Heatmap) GIGANTE
    plt.figure(figsize=(24, 18)) # ¡Lienzo mucho más grande!

    # Creamos una máscara para ocultar la mitad superior
    mask = np.triu(np.ones_like(matriz_filtrada, dtype=bool))

    # Dibujamos el mapa de calor con texto más pequeño
    sns.heatmap(matriz_filtrada, mask=mask, annot=True, fmt=".2f",
                cmap="Reds", vmin=umbral, vmax=1,
                square=True, linewidths=.5,
                cbar_kws={"shrink": .8},
                annot_kws={"size": 8}) # ¡Reducimos el tamaño de la letra de los números!

    plt.title(f'Mapa de Correlaciones (Umbral > {umbral})', fontsize=20, pad=20)
    plt.xticks(rotation=45, ha='right', fontsize=10)
    plt.yticks(fontsize=10)
    plt.tight_layout()
    plt.show()

